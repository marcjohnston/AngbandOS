using System.Reflection;
using AngbandOS.Core.Interface.Metadata;
using AngbandOS.Core.Interface.Configuration;
using AngbandOS.Core.Interface.Configuration.Annotations;
using AngbandOS.Core.Interface;

try
{
    string outputFolder = GetOutputFolderFromCommandLine(args);

    // Enumerate the game configuration object and generate the property metadatas.
    List<Type> reachableTypes = new();

    PropertyMetadata[] propertyMetadatas = ScaffoldType(typeof(GameConfiguration), ref reachableTypes);
    if (propertyMetadatas.Length == 0)
    {
        throw new Exception($"No properties were found in the {nameof(GameConfiguration)} type.");
    }

    ValidateForeignKeyCollectionsExist(propertyMetadatas);

    // Now build the enum metadata.
    Dictionary<string, (string Name, int Value)[]> enumerationsDictionary = GenerateEnumMetadata(propertyMetadatas);

    // Now we have the property metadata for the GameConfiguration.  We need to write the files to disk.  First step is to purge the old
    // folder and create a new one.
    PurgeFolderAndCreateNew(outputFolder);

    // Write the top-level game-configuration type.  The separate collection files are also written.
    WriteMetadataFile(outputFolder, nameof(GameConfiguration), (StreamWriter _writer) =>
    {
        // Write the enumerations into the top-level game configuration type.
        WriteEnumMetadata(_writer, enumerationsDictionary);

        // Now write all of the metadata properties.
        WriteMetadataProperty(_writer, propertyMetadatas, outputFolder);
    });

    Console.WriteLine($"Generated {reachableTypes.Count} metadata classes in '{outputFolder}'.");
    return 0;
}
catch (Exception ex)
{
    // Unsuccessful run.  Errors generated.
    Console.Error.WriteLine(ex.Message);
    return 1;
}
static void WriteMetadataFile(string outputFolder, string classNamePrefix, Action<StreamWriter> callBack)
{
    // Add the path to it.
    string outputPath = Path.Combine(outputFolder, $"{classNamePrefix}Metadata.cs");
    using StreamWriter writer = new(outputPath, false);

    writer.WriteLine($"// <auto-generated>");
    writer.WriteLine($"// This code was generated by scaffold-metadata.");
    writer.WriteLine($"// Changes to this file may cause incorrect behavior and will be lost if the code is regenerated.");
    writer.WriteLine($"// </auto-generated>");
    writer.WriteLine($"namespace {typeof(PropertyMetadata).Namespace};"); // The namesace will be the same as the PropertyMetadata type.
    writer.WriteLine($"public static class {classNamePrefix}Metadata");
    writer.WriteLine($"{{");

    callBack(writer);

    writer.WriteLine($"}}");
}

static void WriteMetadataProperty(StreamWriter writer, PropertyMetadata[] propertyMetadatas, string outputFolder)
{
    writer.WriteLine($"    public static {nameof(PropertyMetadata)}[] Metadata");
    writer.WriteLine($"    {{");
    writer.WriteLine($"        get");
    writer.WriteLine($"        {{");
    writer.WriteLine($"            return new {nameof(PropertyMetadata)}[]");
    writer.WriteLine($"            {{");

    // Now write the property metadata to class files.
    foreach (PropertyMetadata propertyMetadata in propertyMetadatas)
    {
        // Write the property metadata, but collections will persist in a separate file.
        if (propertyMetadata.Type == "collection")
        {
            // These are for the collections.  Collections are scaffolded to separate files so write the metadata with a reference.
            WritePropertyMetadata(writer, propertyMetadata, 4, true);

            // Now write the separate file.
            WriteMetadataFile(outputFolder, propertyMetadata.PropertyName, (StreamWriter _writer) =>
            {
                WriteMetadataProperty(_writer, propertyMetadata.AssociatedProperties!, outputFolder);
            });
        }
        else
        {
            // These are for game setting foreign keys, tuples and arrays.
            WritePropertyMetadata(writer, propertyMetadata, 4, false);
        }
    }

    writer.WriteLine($"            }};");
    writer.WriteLine($"        }}");
    writer.WriteLine($"    }}");
}

static void WritePropertyMetadata(StreamWriter writer, PropertyMetadata propertyMetadata, int indent, bool scaffoldAssociatedPropertiesAsSeparateType)
{
    string indentation = new(' ', 4 * indent);

    writer.WriteLine($"{indentation}new {nameof(PropertyMetadata)}()");
    writer.WriteLine($"{indentation}{{");
    writer.WriteLine($"{indentation}    PropertyName = \"{Escape(propertyMetadata.PropertyName)}\",");
    writer.WriteLine($"{indentation}    Type = \"{Escape(propertyMetadata.Type)}\",");
    if (propertyMetadata.Title is not null)
    {
        writer.WriteLine($"{indentation}    Title = \"{Escape(propertyMetadata.Title)}\",");
    }
    if (propertyMetadata.CategoryTitle != "")
    {
        writer.WriteLine($"{indentation}    CategoryTitle = \"{Escape(propertyMetadata.CategoryTitle)}\",");
    }
    if (propertyMetadata.LabelIfNullable is not null)
    {
        writer.WriteLine($"{indentation}    LabelIfNullable = \"{Escape(propertyMetadata.LabelIfNullable)}\",");
    }
    if (propertyMetadata.Description != "")
    {
        writer.WriteLine($"{indentation}    Description = \"{Escape(propertyMetadata.Description)}\",");
    }
    if (propertyMetadata.EntityKeyPropertyName is not null)
    {
        writer.WriteLine($"{indentation}    EntityKeyPropertyName = \"{Escape(propertyMetadata.EntityKeyPropertyName)}\",");
    }
    if (propertyMetadata.EntityNamePropertyName is not null)
    {
        writer.WriteLine($"{indentation}    EntityNamePropertyName = \"{Escape(propertyMetadata.EntityNamePropertyName)}\",");
    }
    if (propertyMetadata.EntityNounTitle is not null)
    {
        writer.WriteLine($"{indentation}    EntityNounTitle = \"{Escape(propertyMetadata.EntityNounTitle)}\",");
    }
    if (propertyMetadata.ForeignCollectionName is not null)
    {
        writer.WriteLine($"{indentation}    ForeignCollectionName = \"{Escape(propertyMetadata.ForeignCollectionName)}\",");
    }
    if (propertyMetadata.DefaultValue is not null)
    {
        string[] stringValues = propertyMetadata.DefaultValue.Select(value => value is null ? "null" : $"\"{Escape(value)}\"").ToArray();
        string stringList = string.Join(", ", stringValues);
        writer.WriteLine($"{indentation}    DefaultValue = new string?[] {{ {stringList} }},");
    }
    if (propertyMetadata.Inline is not null)
    {
        writer.WriteLine($"{indentation}    Inline = {propertyMetadata.Inline.ToString()!.ToLowerInvariant()},");
    }
    if (propertyMetadata.AssociatedProperties is not null)
    {
        if (!scaffoldAssociatedPropertiesAsSeparateType)
        {
            writer.WriteLine($"{indentation}    AssociatedProperties = new {nameof(PropertyMetadata)}[]");
            writer.WriteLine($"{indentation}    {{");
            foreach (PropertyMetadata associatedPropertyMetadata in propertyMetadata.AssociatedProperties)
            {
                WritePropertyMetadata(writer, associatedPropertyMetadata, indent + 2, false);
            }
            writer.WriteLine($"{indentation}    }},");
        }
        else
        {
            writer.WriteLine($"{indentation}    AssociatedProperties = {propertyMetadata.PropertyName}Metadata.Metadata,");
        }
    }
    writer.WriteLine($"{indentation}}},");
}

static void WriteEnumMetadata(StreamWriter writer, Dictionary<string, (string Name, int Value)[]> enumerationsDictionary)
{
    writer.WriteLine("    public static EnumMetadata[] Enums");
    writer.WriteLine("    {");
    writer.WriteLine("        get");
    writer.WriteLine("        {");
    writer.WriteLine("            return new EnumMetadata[]");
    writer.WriteLine("            {");

    foreach (KeyValuePair<string, (string Name, int Value)[]> enumerationNameAndTuples in enumerationsDictionary)
    {
        writer.WriteLine($"                new EnumMetadata(\"{Escape(enumerationNameAndTuples.Key)}\", new EnumOptionMetadata[]");
        writer.WriteLine("                {");

        foreach ((string Name, int Value) in enumerationNameAndTuples.Value)
        {
            writer.WriteLine($"                    new(\"{Escape(Name)}\", {Value}),");
        }

        writer.WriteLine("                }),");
    }

    writer.WriteLine("            };");
    writer.WriteLine("        }");
    writer.WriteLine("    }");
    writer.WriteLine();
}

static string[] GetEnumPropertyNames(PropertyMetadata[] propertyMetadatas)
{
    List<string> enumPropertyNames = new();

    foreach (PropertyMetadata propertyMetadata in propertyMetadatas)
    {
        if (propertyMetadata.Type == "enum")
        {
            enumPropertyNames.Add(propertyMetadata.ForeignCollectionName);
        }

        if (propertyMetadata.AssociatedProperties is not null)
        {
            string[] associatedPropertiesEnumNames = GetEnumPropertyNames(propertyMetadata.AssociatedProperties);
            enumPropertyNames.AddRange(associatedPropertiesEnumNames);
        }
    }

    return enumPropertyNames.ToArray();
}

static Dictionary<string, (string Name, int Value)[]> GenerateEnumMetadata(PropertyMetadata[] propertyMetadatas)
{
    // Now gather all of the enumerations by name.
    string[] enumPropertyNames = GetEnumPropertyNames(propertyMetadatas).Distinct().ToArray();

    // Retrieve the assembly where the enums are stored.  We use ColorEnum, because it is in the .Interface project.
    Assembly assembly = typeof(ColorEnum).Assembly;

    // Now build the enum metadata.
    Dictionary<string, (string Name, int Value)[]> enumerationsDictionary = new();
    foreach (string enumPropertyName in enumPropertyNames.OrderBy(_enumPropertyName => _enumPropertyName))
    {
        // We need to get the type for the enumeration so that we can generate the metadata for all of the items.  The enumeration should exist within the same
        // assembly as the GameConfiguration assembly (which is the Configuration project).
        Type enumType = assembly.GetTypes().Single(type => type.IsEnum && type.Name == enumPropertyName);

        // Now we need to get the values and cast them into an enum so that we can generate tuples.
        Enum[] enumValues = Enum.GetValues(enumType).Cast<Enum>().ToArray();

        // Now generate tuples.
        (string Name, int Value)[] enumItems = enumValues.Select(value => (Name: value.ToString(), Value: Convert.ToInt32(value))).ToArray();

        // Add it to the dictionary.
        enumerationsDictionary.Add(enumPropertyName, enumItems);
    }
    return enumerationsDictionary;
}

static void ValidateForeignKeyCollectionsExist(PropertyMetadata[] propertyMetadatas)
{
    // Now we need to validate that the foreign keys have matching collections.  Gather all of the foreign key collection names that were 
    // specified.
    string[] foreignKeyCollectionNames = propertyMetadatas
        .Where(propertyMetadata => propertyMetadata.Type == "foreign-key")
        .Select(propertyMetadata => propertyMetadata.ForeignCollectionName!) // This is already verified ... so we use !.
        .Distinct()
        .ToArray();

    // Now ensure those foreign collections exist.
    string[] missingForeignCollectionNames = foreignKeyCollectionNames.Where(foreignCollectionName => !propertyMetadatas.Any(propertyMetadata => propertyMetadata.ForeignCollectionName == foreignCollectionName)).ToArray();
    if (missingForeignCollectionNames.Length > 0)
    {
        throw new Exception($"The {String.Join(", ", missingForeignCollectionNames)} foreign collections do not exist.");
    }
}

static string GetOutputFolderFromCommandLine(string[] args)
{
    // Validate a parameter was sent on the command line.
    if (args.Length != 1)
    {
        string currentExecutableName = Path.GetFileNameWithoutExtension(Environment.ProcessPath) ?? "scaffold-metadata";
        throw new Exception($"syntax: {currentExecutableName} {{output_folder}}");
    }

    string outputFolder = Path.GetFullPath(args[0]);

    // Ensure the output folder isn't a file that we do not want to accidentally overwrite or delete.
    if (File.Exists(outputFolder))
    {
        throw new Exception($"The output path '{outputFolder}' is a file. The output path must be either nonexistent or an existing directory.");
   }
    return outputFolder;
}

static void PurgeFolderAndCreateNew(string outputFolder)
{
    if (Directory.Exists(outputFolder))
    {
        try
        {
            Directory.Delete(outputFolder, recursive: true);
        }
        catch (Exception exception)
        {
            throw new Exception($"Unable to delete existing output directory '{outputFolder}': {exception.Message}");
        }
    }
    Directory.CreateDirectory(outputFolder);
}

static PropertyMetadata[] ScaffoldType(Type type, ref List<Type> reachableTypes)
{
    // Collections are only allowed on the top level configuration object.
    bool collectionsSupported = reachableTypes.Count == 0;

    // Ensure we are not traversing a type that has already been traversed.
    if (reachableTypes.Contains(type))
    {
        throw new Exception($"Configuration type '{type.FullName}' contains a recursive property relationship.");
    }
    reachableTypes.Add(type);

    // Retrieve all of the properties for the type we are traversing and that they are get/set properties.
    PropertyInfo[] properties = type
        .GetProperties(
            BindingFlags.Instance |
            BindingFlags.Public |
            BindingFlags.DeclaredOnly)
        .Where(x => x.CanRead && x.CanWrite)
        .OrderBy(x => x.MetadataToken)
        .ToArray();

    // We need a list to gather all of the return values.
    List<PropertyMetadata> associatedProperties = new();

    // Enumerate all properties of the configuration type and traverse any properties that are themselves configuration types.
    foreach (PropertyInfo property in properties)
    {
        // We use the property name from reflection.
        string propertyName = property.Name;

        // Check to see if this is a collection.  Collections are mutually exclusive with other attributes, except for the ConfigurationCategoryAttribute.
        ConfigurationCollectionAttribute? configurationCollectionAttribute = property.GetCustomAttribute<ConfigurationCollectionAttribute>();
        if (configurationCollectionAttribute is not null)
        {
            // Collections are only supported on the GameConfiguration object.
            if (!collectionsSupported)
            {
                throw new Exception($"The property '{type.Name}.{propertyName}' is a collection but collections are only supported on the GameConfiguration object.");
            }

            ConfigurationForeignKeyAttribute? configurationForeignKeyAttribute = property.GetCustomAttribute<ConfigurationForeignKeyAttribute>();
            if (configurationForeignKeyAttribute is not null)
            {
                throw new Exception($"The property '{type.Name}.{propertyName}' is a collection but collections cannot have foreign keys.");
            }

            ConfigurationTupleItemAttribute[]? configurationTupleItemAttributes = property.GetCustomAttributes<ConfigurationTupleItemAttribute>().ToArray();
            if (configurationTupleItemAttributes.Length > 0)
            {
                throw new Exception($"The property '{type.Name}.{propertyName}' is a collection but collections cannot have tuple item attributes.");
            }

            // Use Reflection to retrieve the collection type, ensure it is an array and determine if it is nullable.
            if (!property.PropertyType.IsArray)
            {
                throw new Exception($"The property '{type.Name}.{propertyName}' is a collection but collections must be of type List<T>.");
            }
            Type arrayType = property.PropertyType;
            Type collectionType = arrayType.GetElementType()!;
            NullabilityInfo nullability = new NullabilityInfoContext().Create(property);
            bool isNullable = nullability.ReadState == NullabilityState.Nullable;

            // Generate the property metadata for the collection.
            PropertyMetadata[] collectionPropertyMetadata = ScaffoldType(collectionType, ref reachableTypes);

            // Generate the parent property metadata for the collection property.
            PropertyMetadata propertyMetadata = new()
            {
                Type = "collection",
                PropertyName = propertyName,
                Title = configurationCollectionAttribute.Title,
                LabelIfNullable = configurationCollectionAttribute.LabelIfNullable,
                Description = configurationCollectionAttribute.Summary ?? "",
                EntityKeyPropertyName = "GetKey",
                EntityNamePropertyName = configurationCollectionAttribute.EntityNamePropertyName ?? "GetKey",
                EntityNounTitle = configurationCollectionAttribute.EntityNounTitle,
                ForeignCollectionName = configurationCollectionAttribute.CollectionName,
                AssociatedProperties = collectionPropertyMetadata
            };

            // If there is a category attribute, then we will use it to override the category title.
            ConfigurationCategoryAttribute? configurationCategoryAttribute = property.GetCustomAttribute<ConfigurationCategoryAttribute>();
            if (configurationCategoryAttribute is not null)
            {
                propertyMetadata.CategoryTitle = configurationCategoryAttribute.Title;
            }

            associatedProperties.Add(propertyMetadata);
        }
        else
        {
            // This is not a collection.  Retrieve the ConfigurationPropertyAttribute metadata for the property.
            ConfigurationPropertyAttribute? configurationPropertyAttribute = property.GetCustomAttribute<ConfigurationPropertyAttribute>();

            // Every property must have a ConfigurationPropertyAttribute. If it does not, then it is not a valid configuration property and we will skip it.
            if (configurationPropertyAttribute is null)
            {
                throw new Exception($"Property '{type.FullName}.{propertyName}' is not annotated with either the {nameof(ConfigurationCollectionAttribute)} or the {nameof(ConfigurationPropertyAttribute)}.");
            }

            // Parse the annotated data type.  This applies to both the collection and non-collection properties.
            string? annotatedDataTypeAsString = configurationPropertyAttribute.DataType;
            if (annotatedDataTypeAsString is null)
            {
                throw new Exception($"The property '{type.Name}.{propertyName}' has no DataType.");
            }

            // We need to parse the data type.  This parsing will throw (needed for unit testing), so we need to convert those exceptions to error messages
            // and exit cleanly.
            AnnotatedDataType annotatedDataType;
            try
            {
                annotatedDataType = AnnotatedDataType.Parse(annotatedDataTypeAsString);
            }
            catch (Exception ex)
            {
                throw new Exception($"Error occured parsing the data type for property {type.Name}.{property.Name}. {ex.Message}");
            }

            // Assert that the annotated data type is valid for the property type.
            if (annotatedDataType.ToString() != annotatedDataTypeAsString)
            {
                throw new Exception($"Unable to parse the DataType '{annotatedDataTypeAsString}' for the '{type.Name}.{propertyName}' property.");
            }

            // Generate the property metadata for the collection property.
            PropertyMetadata propertyMetadata = annotatedDataType.ToPropertyMetadata();

            // Copy the ConfigurationPropertyAttribute properties.
            propertyMetadata.PropertyName = propertyName;
            propertyMetadata.Title = configurationPropertyAttribute.Title;
            propertyMetadata.LabelIfNullable = configurationPropertyAttribute.LabelIfNullable;
            propertyMetadata.Description = configurationPropertyAttribute.Description ?? "";

            // If there is a category attribute, then we will use it to override the category title.
            ConfigurationCategoryAttribute? configurationCategoryAttribute = property.GetCustomAttribute<ConfigurationCategoryAttribute>();
            if (configurationCategoryAttribute is not null)
            {
                propertyMetadata.CategoryTitle = configurationCategoryAttribute.Title;
            }

            // If there is a foreign key attribute, then we will use it to override the associated properties
            ConfigurationForeignKeyAttribute? configurationForeignKeyAttribute = property.GetCustomAttribute<ConfigurationForeignKeyAttribute>();
            if (configurationForeignKeyAttribute is not null)
            {
                // Check to see if this is an array, where the subtype is the foreign key.
                PropertyMetadata stringPropertyMetadata;
                // Check to see if the property metadata is a string.
                if (propertyMetadata.Type == "string")
                {
                    stringPropertyMetadata = propertyMetadata;
                }
                else if ((propertyMetadata.Type == "array" || propertyMetadata.Type == "2d-array") && propertyMetadata.AssociatedProperties is not null && propertyMetadata.AssociatedProperties.Length == 1 && propertyMetadata.AssociatedProperties[0].Type == "string")
                {
                    // Convert the associated property type to a foreign-key.
                    stringPropertyMetadata = propertyMetadata.AssociatedProperties[0];
                }
                else
                {
                    throw new Exception($"The property '{type.Name}.{propertyName}' is a foreign key but foreign keys must be of type string.");
                }
                // Convert the type to a foreign-key.
                stringPropertyMetadata.Type = "foreign-key";
                stringPropertyMetadata.ForeignCollectionName = configurationForeignKeyAttribute.CollectionName;
                stringPropertyMetadata.Inline = configurationForeignKeyAttribute.Inline;
            }

            // If there are tuples, then we will use them to override the associated properties.
            ConfigurationTupleItemAttribute[]? configurationTupleItemAttributes = property.GetCustomAttributes<ConfigurationTupleItemAttribute>().ToArray();
            if (configurationTupleItemAttributes is not null)
            {
                // Generate a dictionary for easy lookup.
                Dictionary<string, ConfigurationTupleItemAttribute> configurationTupleItemAttributeDictionary = configurationTupleItemAttributes.ToDictionary(x => x.Name, x => x);

                // Recursively populate the PropertyMetadata with the associated tuple items.
                CopyConfigurationTupleItemAttributes(propertyMetadata, "", configurationTupleItemAttributeDictionary);

                // Ensure all of the dictionary items were matched.
                if (configurationTupleItemAttributeDictionary.Count > 0)
                {
                    throw new Exception($"The property '{type.Name}.{propertyName}' has tuple items that did not match any tuple item.");
                }
            }

            associatedProperties.Add(propertyMetadata);
        }
    }
    return associatedProperties.ToArray();
}

static void CopyConfigurationTupleItemAttributes(PropertyMetadata propertyMetadata, string propertyNamePrefix, Dictionary<string, ConfigurationTupleItemAttribute> configurationTupleItemAttributeDictionary)
{
    // If the property metadata type is an array or 2d-array, then copy the properties to the inner type.
    if (propertyMetadata.Type == "array" || propertyMetadata.Type == "2d-array")
    {
        // The associated properties for an array must be populated with exactly 1 element.
        if (propertyMetadata.AssociatedProperties is null || propertyMetadata.AssociatedProperties.Length != 1)
        {
            throw new Exception($"Exactly one associated property is expected for the array property '{propertyMetadata.PropertyName}'.");
        }

        CopyConfigurationTupleItemAttributes(propertyMetadata.AssociatedProperties[0], propertyNamePrefix, configurationTupleItemAttributeDictionary);
        return;
    }

    // If the property metadata isn't a tuple, then no processing occurs.  This allows us to recurse the property metadata to determine eligibility.
    if (propertyMetadata.Type != "tuple")
    {
        return;
    }

    // The associated properties for a tuple must be populated with at least 1 element.
    if (propertyMetadata.AssociatedProperties is null || propertyMetadata.AssociatedProperties.Length == 0)
    {
        throw new Exception($"At least one associated property is expected for the tuple property '{propertyMetadata.PropertyName}'.");
    }

    // Enumerate the tuple items.
    foreach (PropertyMetadata associatedPropertyMetadata in propertyMetadata.AssociatedProperties)
    {
        // Concatenate the parent/prefix name with the current property name for the lookup.
        string targetPropertyName = $"{propertyNamePrefix}{associatedPropertyMetadata.PropertyName}";

        // Retrieve the tuple item attribute for the associated property metadata.
        ConfigurationTupleItemAttribute? configurationTupleItemAttribute = configurationTupleItemAttributeDictionary.GetValueOrDefault(targetPropertyName);

        // Ensure the tuple item attribute exists for the associated property metadata.
        if (configurationTupleItemAttribute is null)
        {
            throw new Exception($"The tuple item attribute for the property '{targetPropertyName}' was not found.");
        }

        // Remove the tuple item from the dictionary, now that we used it.
        configurationTupleItemAttributeDictionary.Remove(targetPropertyName);

        // Copy the properties.
        associatedPropertyMetadata.Title = configurationTupleItemAttribute.Title;
        associatedPropertyMetadata.Description = configurationTupleItemAttribute.Description ?? "";
        associatedPropertyMetadata.Inline = configurationTupleItemAttribute.Inline;
        associatedPropertyMetadata.LabelIfNullable = configurationTupleItemAttribute.LabelIfNullable;

        // The foreign collection name is being shared with enum name.  Enums can't be strings and foreign-keys can only be strings.
        // We need to preserve the ForeignCollectionName, when the tuple item attribute is null.
        associatedPropertyMetadata.ForeignCollectionName = configurationTupleItemAttribute.ForeignCollectionName ?? associatedPropertyMetadata.ForeignCollectionName;

        // Recurively check for nested tuples.  Since the call can do the check and return when not applicable, we can simple make the recursive vall.
        CopyConfigurationTupleItemAttributes(associatedPropertyMetadata, targetPropertyName, configurationTupleItemAttributeDictionary);
    }
}

static string Escape(string value)
{
    return value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n");
}